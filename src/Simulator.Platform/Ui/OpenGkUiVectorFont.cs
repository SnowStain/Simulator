namespace Simulator.Platform.Ui;

public readonly record struct OpenGkUiVectorGlyph(IReadOnlyList<string> Rows)
{
    public int Width => Rows.Count == 0 ? 0 : Rows[0].Length;

    public int Height => Rows.Count;
}

public static class OpenGkUiVectorFont
{
    public static float ResolveScale(OpenGkUiTextStyle style)
        => style switch
        {
            OpenGkUiTextStyle.Tiny => 1.5f,
            OpenGkUiTextStyle.HudMid => 2.4f,
            OpenGkUiTextStyle.HudBig => 3.0f,
            OpenGkUiTextStyle.MenuSubtitle => 2.0f,
            OpenGkUiTextStyle.MenuButton => 2.2f,
            _ => 1.8f,
        };

    public static float MeasureText(string text, float scale)
    {
        float width = 0.0f;
        foreach (char original in text)
        {
            OpenGkUiVectorGlyph glyph = ResolveGlyph(original);
            width += (glyph.Width + 1) * scale;
        }

        return MathF.Max(0.0f, width - scale);
    }

    public static OpenGkUiVectorGlyph ResolveGlyph(char c)
        => Glyphs.TryGetValue(char.ToUpperInvariant(c), out string[]? glyph)
            ? new OpenGkUiVectorGlyph(glyph)
            : new OpenGkUiVectorGlyph(UnknownGlyph);

